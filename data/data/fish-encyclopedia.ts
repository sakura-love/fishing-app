export const getFishById = (id: string): FishSpecies | undefined => {
  return fishEncyclopedia.find((fish) => fish.id === id);
};

export const getFishByCategory = (category: 'freshwater' | 'saltwater'): FishSpecies[] => {
  return fishEncyclopedia.filter((fish) => fish.category === category);
};

export const searchFish = (query: string): FishSpecies[] => {
  const q = query.toLowerCase();
  return fishEncyclopedia.filter(
    (fish) =>
      fish.name.includes(q) ||
      fish.scientificName.toLowerCase().includes(q) ||
      fish.family.includes(q)
  );
};

export const getFishForWaterTemp = (temp: number): FishSpecies[] => {
  return fishEncyclopedia.filter(
    (fish) => temp >= fish.optimalTemp.min - 5 && temp <= fish.optimalTemp.max + 5
  );
};
